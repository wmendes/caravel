#!/usr/bin/env node
// Writes the docs site's CLI reference from `caravel help` (M0.7, H-12,
// DEC-100): one page per command and subcommand, and an index grouping them.
// The help text is the source; scripts/check-cli-docs.sh fails when the
// pages and the binary disagree.
//
//   node scripts/gen-cli-docs.mjs [path/to/caravel]     (default: target/release/caravel)
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const bin = process.argv[2] ?? process.env.CARAVEL_BIN ?? join(root, "target/release/caravel");
const out = join(root, "docs-site/docs/reference/cli");

// How the index groups the commands; a command missing here goes to "Other".
const GROUPS = [
  ["Deploy and change a lane", ["plan", "apply", "status", "destroy", "graph"]],
  ["Check a lane file", ["validate", "render", "env", "output", "doctor", "version"]],
  ["Run the nodes", ["start", "stop", "restart", "logs", "wait", "api", "replay"]],
  ["Use a lane", ["account", "balance", "deposit", "tx", "withdraw", "claim", "force-withdraw", "escape"]],
  ["Start a lane", ["init", "keys"]],
];

const help = (...args) => execFileSync(bin, ["help", ...args], { encoding: "utf8", env: { ...process.env, NO_COLOR: "1" } });

// "Commands:" lines → [name, summary]; `help` itself is left out.
function commands(text) {
  const block = text.split(/^Commands:\n/m)[1];
  if (!block) return [];
  return block
    .split(/\n\n/)[0]
    .split("\n")
    .map((l) => l.match(/^ {2}([\w-]+)\s{2,}(.*)$/))
    .filter((m) => m && m[1] !== "help")
    .map((m) => [m[1], m[2].trim()]);
}

const firstLine = (text) => text.split("\n")[0].trim();
const yaml = (s) => JSON.stringify(s);

// A command with subcommands is a folder: its page is the folder's index,
// and each subcommand a page beside it.
function page(path, dir, position) {
  const text = help(...path).replace(/\s+$/, "") + "\n";
  const subs = commands(text);
  const file = subs.length ? join(dir, path[path.length - 1], "index.md") : join(dir, `${path[path.length - 1]}.md`);
  const name = `caravel ${path.join(" ")}`;
  let md = `---\ntitle: ${yaml(name)}\nsidebar_label: ${yaml(path.join(" "))}\nsidebar_position: ${position}\ndescription: ${yaml(firstLine(text))}\n---\n\n`;
  md += `<!-- Generated by scripts/gen-cli-docs.mjs from \`caravel help ${path.join(" ")}\`. Do not edit. -->\n\n`;
  md += `${firstLine(text)}\n\n\`\`\`text\n${text}\`\`\`\n`;
  if (subs.length) {
    md += `\n## Subcommands\n\n| Command | What it does |\n|---|---|\n`;
    for (const [s, what] of subs) md += `| [\`${name} ${s}\`](./${s}.md) | ${what.replace(/\|/g, "\\|")} |\n`;
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, md);
  if (subs.length) {
    const sub = join(dir, path[path.length - 1]);
    writeFileSync(join(sub, "_category_.json"), JSON.stringify({ label: path.join(" "), position }, null, 2) + "\n");
    subs.forEach(([s], k) => page([...path, s], sub, k + 1));
  }
  return subs;
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const top = commands(help());
const known = new Set(GROUPS.flatMap(([, cs]) => cs));
const groups = [...GROUPS, ["Other", top.map(([c]) => c).filter((c) => !known.has(c))]].filter(([, cs]) => cs.length);
const summary = new Map(top);
let index = `---\ntitle: CLI reference\nsidebar_label: Overview\nsidebar_position: 0\ndescription: "Every caravel command, generated from the CLI's own help."\n---\n\n`;
index += `<!-- Generated by scripts/gen-cli-docs.mjs from \`caravel help\`. Do not edit. -->\n\n`;
index += "`caravel` is one CLI for every template. Each command finds `lane.toml` in the current directory (or `-f`) and uses its default deployment (or `--env`). Every command takes `--json`, which prints JSON on stdout for scripts while progress goes to stderr.\n\n";
index += "These pages are generated from `caravel help`, so they match the binary they were built from.\n";
let pos = 1;
for (const [title, cs] of groups) {
  index += `\n## ${title}\n\n| Command | What it does |\n|---|---|\n`;
  for (const c of cs) {
    if (!summary.has(c)) continue;
    const subs = page([c], out, pos++);
    index += `| [\`caravel ${c}\`](./${subs.length ? `${c}/index.md` : `${c}.md`}) | ${summary.get(c).replace(/\|/g, "\\|")} |\n`;
  }
}
writeFileSync(join(out, "index.md"), index);
writeFileSync(join(out, "_category_.json"), JSON.stringify({ label: "CLI", position: 2, link: { type: "doc", id: "reference/cli/index" } }, null, 2) + "\n");
const count = (d) => readdirSync(d, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? count(join(d, e.name)) : e.name.endsWith(".md") ? 1 : 0), 0);
console.log(`wrote ${count(out)} pages to docs-site/docs/reference/cli`);
